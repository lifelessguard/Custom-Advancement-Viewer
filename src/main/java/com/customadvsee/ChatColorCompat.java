package com.customadvsee;

import org.bukkit.ChatColor;

public class ChatColorCompat {
    public static String gold(String s) { return ChatColor.GOLD + s; }
    public static String aqua(String s) { return ChatColor.AQUA + s; }
    public static String gray(String s) { return ChatColor.GRAY + s; }
    public static String yellow(String s) { return ChatColor.YELLOW + s; }
}
